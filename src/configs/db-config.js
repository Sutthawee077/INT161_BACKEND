/**
 * ==============================================================================================
 * 📁 File: src/configs/db-config.js
 * 🏷️ Layer: Configuration (การตั้งค่าระบบและฐานข้อมูล)
 * ==============================================================================================
 * 
 * 📖 วัตถุประสงค์ของไฟล์นี้:
 * ไฟล์นี้ทำหน้าที่สร้างและ Export ออบเจกต์ "Connection Pool" สำหรับเชื่อมต่อไปยังฐานข้อมูล MySQL
 * โดยใช้ไลบรารี 'mysql2/promise' ซึ่งรองรับไวยากรณ์ async/await ยุคใหม่ของ JavaScript (ES Modules)
 * 
 * ----------------------------------------------------------------------------------------------
 * ❓ ทำไมต้องใช้ Connection Pool (createPool) แทนการต่อตรง (createConnection)?
 * ----------------------------------------------------------------------------------------------
 * 1. ประสิทธิภาพ (Performance):
 *    - การเปิด Connection ใหม่ทุกครั้งที่มี HTTP Request เข้ามามีต้นทุนสูง (Handshake, Authentication)
 *    - Connection Pool จะเปิด Connection ล่วงหน้าไว้ตามจำนวนที่กำหนด (เช่น 10 connections)
 *    - เมื่อมี Request เข้ามา จะ "ยืม" Connection ที่ว่างไปใช้ เมื่อทำงานเสร็จจะ "คืน" เข้า Pool ทันที
 * 2. ป้องกันเซิร์ฟเวอร์ล่ม (Concurrency & Throttling):
 *    - หากมี Client ยิงเข้ามาพร้อมกัน 1,000 คน Pool จะจำกัดการเชื่อมต่อไปยัง MySQL ไม่ให้เกินขีดจำกัด
 *    - Request ที่เกินจะถูกจัดคิวรออย่างเป็นระเบียบ ทำให้ฐานข้อมูลไม่ล่มจากภาวะ Overload
 * 
 * ----------------------------------------------------------------------------------------------
 * ⚠️ กับดักข้อสอบยอดฮิต (Exam Pitfalls):
 * ----------------------------------------------------------------------------------------------
 * 🪤 กับดักที่ 1: การคืนค่าฟิลด์ DECIMAL/NUMERIC ใน MySQL
 *    - ค่าเริ่มต้นของไดรเวอร์ mysql2 จะแปลงข้อมูลชนิด DECIMAL (เช่น price 29900.00) ให้เป็น "String"
 *      เช่น "29900.00" เพื่อป้องกันปัญหาปัดเศษของ JavaScript Float
 *    - แต่ในข้อสอบ Backend และชุดเทสอัตโนมัติ (เช่น test_api.py) คาดหวังว่าฟิลด์ price จะต้องเป็น "Number"
 *    - 👉 ทางแก้: ต้องใส่ option `decimalNumbers: true` เพื่อบังคับให้คืนค่าออกมาเป็น Number ทันที
 * 
 * 🪤 กับดักที่ 2: Hardcode รหัสผ่านและพอร์ต
 *    - ห้ามเขียนค่าคงที่ตายตัวโดยไม่เปิดช่องทางให้ override ผ่าน Environment Variables (process.env)
 *    - ในการสอบ เครื่องอาจารย์อาจใช้พอร์ตหรือรหัสผ่านที่ต่างจากเครื่องของเรา
 *    - 👉 ทางแก้: ใช้รูปแบบ `process.env.DB_VAR || 'default_value'`
 * ==============================================================================================
 */

import mysql from 'mysql2/promise';

/**
 * สร้าง Connection Pool ไปยัง MySQL Server
 */
const pool = mysql.createPool({
  // ที่อยู่ของ MySQL Server: ค่าเริ่มต้นคือ 'localhost' (เครื่องตัวเอง)
  host: process.env.DB_HOST || 'localhost',

  // พอร์ตมาตรฐานของ MySQL คือ 3306
  // ใช้ parseInt แปลงสตริงจาก process.env ให้เป็นตัวเลขฐาน 10
  port: parseInt(process.env.DB_PORT || '3306', 10),

  // บัญชีผู้ใช้งานฐานข้อมูล (เริ่มต้นของเครื่องนักศึกษาส่วนใหญ่คือ 'root')
  user: process.env.DB_USER || 'root',

  // รหัสผ่านฐานข้อมูล:
  // ใช้ ternary operator เช็คว่ามีการส่ง DB_PASSWORD มาหรือไม่ (อนุญาตให้รหัสผ่านเป็นค่าว่าง '' ได้)
  password: process.env.DB_PASSWORD !== undefined ? process.env.DB_PASSWORD : 'DearDear.5',

  // ชื่อฐานข้อมูลหลักที่ใช้งานในข้อสอบนี้
  database: process.env.DB_NAME || 'mobile_exam',

  // --------------------------------------------------------------------------------------------
  // Pool Sizing & Queue Behaviors:
  // --------------------------------------------------------------------------------------------
  // เมื่อ Connection เต็มทั้ง 10 ตัว จะให้คำขอใหม่ "รอคิว" จนกว่าจะมี Connection ว่าง (true)
  waitForConnections: true,

  // จำนวน Connection สูงสุดที่อนุญาตให้เปิดค้างไว้ใน Pool พร้อมกัน (ค่าแนะนำสำหรับสอบ: 10)
  connectionLimit: 10,

  // ขีดจำกัดจำนวนคำขอที่เข้าคิวรอ (0 = Unlimited ไม่จำกัดจำนวนคิว เพื่อป้องกันคำขอถูกปฏิเสธ)
  queueLimit: 0,

  // --------------------------------------------------------------------------------------------
  // Type Casting Optimization:
  // --------------------------------------------------------------------------------------------
  // บังคับให้ไดรเวอร์ mysql2 แปลงฟิลด์ DECIMAL และ NUMERIC ใน SQL ให้กลายเป็น JavaScript Number ทันที
  // หากไม่ใส่ค่านี้ เมื่อ Query คอลัมน์ price DECIMAL(10,2) จะได้เป็นสตริง "29900.00" ซึ่งจะทำให้ชุดเทสตรวจตก!
  decimalNumbers: true
});

/**
 * ส่งออก (Export) ออบเจกต์ pool เพื่อให้ Repository Layers นำไปสั่ง query ได้ทั่วทั้งแอปพลิเคชัน
 */
export default pool;

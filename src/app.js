/**
 * ==============================================================================================
 * 📁 File: src/app.js
 * 🏷️ Layer: Application Entry Point & Middleware Pipeline (จุดเริ่มต้นของระบบ)
 * ==============================================================================================
 * 
 * 📖 หน้าที่และความรับผิดชอบของ app.js:
 * 1. กำหนดค่าเริ่มต้นให้กับ Express Application
 * 2. ตั้งค่าความปลอดภัยระดับ HTTP (เช่น ปิดการเปิดเผยเทคโนโลยีด้วย `disable('x-powered-by')`)
 * 3. จัดเรียงลำดับการประมวลผลของ Middleware (Pipeline Flow) ให้ถูกต้อง
 * 4. Mount เส้นทาง API Routers ทั้งหมดในระบบ
 * 5. เชื่อมต่อ Centralized Error Handler ไว้เป็นปราการด่านสุดท้าย
 * 6. สั่ง Listen Port เพื่อเปิดรับ HTTP Request จากภายนอก
 * 
 * ----------------------------------------------------------------------------------------------
 * 🔄 วงจรชีวิตของ HTTP Request ผ่าน Middleware Pipeline (Request Lifecycle):
 * ----------------------------------------------------------------------------------------------
 * 
 *    Client Request (เช่น POST /api/v1/products)
 *            │
 *            ▼
 *    [1. transportValidator]  $\rightarrow$ ตรวจสอบ Content-Type / Accept Headers (415 / 406)
 *            │
 *            ▼
 *    [2. rawBodyParser]       $\rightarrow$ อ่าน Raw Stream, เก็บ req.rawBody, แปลง JSON
 *            │
 *            ▼
 *    [3. brandRouter / productRouter]
 *            │                $\rightarrow$ ตรวจ Path/Query, วิ่งเข้า Service & DB
 *            │
 *            ├─── (ถ้าทำงานสำเร็จ) ───$\rightarrow$ ส่ง Response 200/201/204 กลับ Client ทันที
 *            │
 *            └─── (ถ้าเกิด Error / next(err))
 *                     │
 *                     ▼
 *    [4. errorHandler]        $\rightarrow$ จัดรูป JSON Error Response (400, 404, 409, 500)
 * 
 * ----------------------------------------------------------------------------------------------
 * ⚠️ กฎสำคัญที่สุด: ลำดับการวาง Middleware ใน Express ห้ามสลับกันเด็ดขาด!
 * ==============================================================================================
 */

import express from 'express';
import brandRouter from './routes/brand-route.js';
import productRouter from './routes/product-route.js';
import { transportValidator, rawBodyParser } from './middlewares/transport-middleware.js';
import { errorHandler } from './middlewares/error-handler.js';

// สร้างอินสแตนซ์ของ Express Application
const app = express();

// ----------------------------------------------------------------------------------------------
// การตั้งค่าความปลอดภัย (Security Configuration):
// ----------------------------------------------------------------------------------------------
// ปิดการส่ง Response Header "X-Powered-By: Express" เพื่อป้องกันไม่ให้ผู้ไม่หวังดีทราบประเภทเซิร์ฟเวอร์
app.disable('x-powered-by');

// ----------------------------------------------------------------------------------------------
// ขั้นที่ 1: ตรวจสอบ HTTP Content Negotiation (415 Unsupported Media Type / 406 Not Acceptable)
// ----------------------------------------------------------------------------------------------
app.use(transportValidator);

// ----------------------------------------------------------------------------------------------
// ขั้นที่ 2: แปลง JSON Body พร้อมจัดเก็บ req.rawBody สำหรับดักจับทศนิยมในฟิลด์ Integer
// ----------------------------------------------------------------------------------------------
app.use(rawBodyParser);

// ----------------------------------------------------------------------------------------------
// ขั้นที่ 3: ลงทะเบียน API Routers
// ----------------------------------------------------------------------------------------------
// เส้นทางสำหรับจัดการแบรนด์
app.use('/api/v1/brands', brandRouter);

// เส้นทางสำหรับจัดการสินค้า
app.use('/api/v1/products', productRouter);

// ----------------------------------------------------------------------------------------------
// ขั้นที่ 4: Centralized Error Handler (ดักจับ Error รวมศูนย์)
// ⚠️ ต้องวางไว้เป็นลำดับสุดท้ายหลัง Routers ทั้งหมดเสมอ!
// ----------------------------------------------------------------------------------------------
app.use(errorHandler);

// ----------------------------------------------------------------------------------------------
// ขั้นที่ 5: เริ่มต้นการทำงานของเซิร์ฟเวอร์ (Start Server)
// ----------------------------------------------------------------------------------------------
// กำหนดหมายเลขพอร์ต: ค่าเริ่มต้นคือ 8080 ตามที่ชุดทดสอบอัตโนมัติ (test_api.py) คาดหวัง
const PORT = process.env.PORT || 8080;

app.listen(PORT, () => {
  console.log(`🚀 [INT161 Backend Server] is running on http://localhost:${PORT}`);
});

export default app;
